import type { EffectMilestone, EffectProject } from "./effect-projects";

function lesson(
  id: string,
  title: string,
  concept: string,
  brief: string,
  explanation: string,
  steps: string[],
  checks: string[],
  experiment: string,
  review: string,
  stretch: string,
  minutes = 60,
  stage: EffectMilestone["stage"] = "Make it reliable",
): EffectMilestone {
  return {
    id: `effect-${id}`,
    title,
    concept,
    brief,
    explanation,
    steps,
    checks: checks.map((label, index) => ({
      id: `criterion-${index + 1}`,
      label,
    })),
    experiment,
    review,
    stretch,
    minutes,
    stage,
    skill: "Effect & agentic CRUD",
    study: "TypeScript",
  };
}

